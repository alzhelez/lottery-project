def build_frequency_prediction(pipeline_data, b1_max, b2_max, pick_b1, pick_b2, draws_data=None):
    """v26.0: Build frequency-based prediction using recency-scored numbers.

    From accuracy_history, extract all actual numbers, compute frequency * recency_score,
    and select top numbers for each block.

    v26.0: Added draws_data fallback — when accuracy_history has too few entries,
    uses global frequency from the full draws file.

    Returns:
        {"block1": [...], "block2": [...], "details": {...}}
    """
    accuracy_history = pipeline_data.get('accuracy_history', [])

    # v26.0: Fallback to full draws data if accuracy_history is too small
    if len(accuracy_history) < 10 and draws_data:
        accuracy_history = _convert_draws_to_accuracy_history(draws_data, b1_max, b2_max)

    if not accuracy_history:
        return {"block1": [], "block2": [], "details": {}}

    b1_freq = defaultdict(int)
    b2_freq = defaultdict(int)
    b1_last_seen = {}
    b2_last_seen = {}
    total = len(accuracy_history)

    for i in range(total - 1, -1, -1):
        entry = accuracy_history[i]
        draws_ago = total - 1 - i
        for x in entry.get('act_b1', []):
            if x not in b1_last_seen:
                b1_last_seen[x] = draws_ago
            b1_freq[x] += 1
        for x in entry.get('act_b2', []):
            if x not in b2_last_seen:
                b2_last_seen[x] = draws_ago
            b2_freq[x] += 1

    # Compute recency_score = count * (1 / (1 + last_seen))
    b1_scores = []
    for num in range(1, b1_max + 1):
        if b1_freq[num] > 0:
            count = b1_freq[num]
            last_seen = b1_last_seen.get(num, total)
            recency_score = count * (1.0 / (1 + last_seen))
            b1_scores.append({"number": num, "count": count, "last_seen": last_seen, "recency_score": round(recency_score, 3)})
    b1_scores.sort(key=lambda x: -x["recency_score"])

    b2_scores = []
    for num in range(1, b2_max + 1):
        if b2_freq[num] > 0:
            count = b2_freq[num]
            last_seen = b2_last_seen.get(num, total)
            recency_score = count * (1.0 / (1 + last_seen))
            b2_scores.append({"number": num, "count": count, "last_seen": last_seen, "recency_score": round(recency_score, 3)})
    b2_scores.sort(key=lambda x: -x["recency_score"])

    final_b1 = sorted([s["number"] for s in b1_scores[:pick_b1]])
    final_b2 = sorted([s["number"] for s in b2_scores[:pick_b2]])

    return {
        "block1": final_b1,
        "block2": final_b2,
        "details": {
            "block1": b1_scores[:max(pick_b1 * 3, 10)],
            "block2": b2_scores[:max(pick_b2 * 3, 10)],
        },
    }


def build_top3_models(pipeline_data, model_names_from_predict=None):
    """v25.0: Identify top 3 best-performing models and return their predictions.

    From pipeline_data predictions and accuracy_history, compute per-model accuracy
    and return top 3 models with their current predictions.

    Returns:
        {"models": [{"id": 0, "name": "...", "avg_hits": 3.2, "b1": [...], "b2": [...]}, ...]}
    """
    predictions = pipeline_data.get('predictions', [])
    accuracy_history = pipeline_data.get('accuracy_history', [])
    if not predictions:
        return {"models": []}

    # Compute per-model accuracy from accuracy_history
    # Since accuracy_history only has consensus predictions, approximate by
    # counting how many of each model's predicted numbers appeared in recent actuals.
    model_scores = []
    total_recent = min(len(accuracy_history), 100) if accuracy_history else 0
    recent_actuals_b1 = defaultdict(int)
    recent_actuals_b2 = defaultdict(int)
    for entry in (accuracy_history[-total_recent:] if accuracy_history else []):
        for x in entry.get('act_b1', []):
            recent_actuals_b1[x] += 1
        for x in entry.get('act_b2', []):
            recent_actuals_b2[x] += 1

    for mi, pred in enumerate(predictions):
        b1 = pred.get('b1', [])
        b2 = pred.get('b2', [])
        # Score: sum of actual frequency of predicted numbers
        score = sum(recent_actuals_b1.get(x, 0) for x in b1) + sum(recent_actuals_b2.get(x, 0) for x in b2)
        model_scores.append({
            'id': mi,
            'name': pred.get('name', model_names_from_predict[mi] if model_names_from_predict and mi < len(model_names_from_predict) else f'Model-{mi+1}'),
            'avg_hits': round(score / max(total_recent, 1), 3),
            'b1': sorted(b1),
            'b2': sorted(b2),
        })

    model_scores.sort(key=lambda x: -x['avg_hits'])
    return {"models": model_scores[:3]}


def _convert_draws_to_accuracy_history(draws_data, b1_max, b2_max):
    """v26.0: Convert full draws data to accuracy_history format for frequency fallback."""
    history = []
    for i, d in enumerate(draws_data):
        act_b1 = list(d.get('block1', d.get('b1', []))) if isinstance(d, dict) else []
        act_b2 = list(d.get('block2', d.get('b2', []))) if isinstance(d, dict) else []
        if act_b1:
            history.append({
                'act_b1': act_b1,
                'act_b2': act_b2,
                'pred_b1': [],
                'pred_b2': [],
                'hits_b1': 0,
                'hits_b2': 0,
            })
    return history


def _get_game_hint(game_name: str):
    """Get game format hint for a given game name."""
    if not game_name:
        return None
    name = game_name.replace('draws_', '').replace('tirazh', '').strip()
    for key in (name, name.lower()):
        if key in _PIPELINE_GAME_HINTS:
            return _PIPELINE_GAME_HINTS[key]
    return None


