def analyze_from_pipeline_data(predictions, accuracy_history, b1_max, b2_max,
                                pick_b1, pick_b2, draw_type, top_models, recency):
    """Run position-specific ensemble directly from pipeline data."""
    from collections import defaultdict

    # Build per-position vote counts
    b1_position_votes = defaultdict(lambda: defaultdict(float))
    b2_position_votes = defaultdict(lambda: defaultdict(float))

    for pred in predictions:
        b1 = [int(n) for n in pred.get('b1', [])]
        b2 = [int(n) for n in pred.get('b2', [])]
        for pos_idx, num in enumerate(b1):
            b1_position_votes[pos_idx][num] += 1.0
        for pos_idx, num in enumerate(b2):
            b2_position_votes[pos_idx][num] += 1.0

    # Also compute accuracy-weighted votes
    b1_acc_weighted = defaultdict(lambda: defaultdict(float))
    b2_acc_weighted = defaultdict(lambda: defaultdict(float))

    if accuracy_history:
        # Use recent accuracy to weight predictions
        recent = accuracy_history[-recency:] if len(accuracy_history) > recency else accuracy_history
        total_recent = len(recent) if recent else 1

        for entry in recent:
            pred_b1 = entry.get('pred_b1', [])
            pred_b2 = entry.get('pred_b2', [])
            act_b1 = entry.get('act_b1', [])
            act_b2 = entry.get('act_b2', [])
            hits_b1 = entry.get('hits_b1', 0)
            hits_b2 = entry.get('hits_b2', 0)

            # Weight by hit rate
            w = 1.0 + (hits_b1 + hits_b2) * 0.5  # Higher weight for accurate draws

            for pos_idx, num in enumerate(pred_b1):
                num = int(num)  # Ensure int type
                if num in act_b1:
                    b1_acc_weighted[pos_idx][num] += w * 2.0  # Extra boost for correct predictions
                else:
                    b1_acc_weighted[pos_idx][num] += w * 0.1
            for pos_idx, num in enumerate(pred_b2):
                num = int(num)  # Ensure int type
                if num in act_b2:
                    b2_acc_weighted[pos_idx][num] += w * 2.0
                else:
                    b2_acc_weighted[pos_idx][num] += w * 0.1

    # Select final numbers per position
    final_b1 = []
    b1_used = set()
    b1_details = {}

    for pos_idx in range(pick_b1):
        # Combine vote-based and accuracy-weighted scores
        combined_votes = defaultdict(float)
        for num, cnt in b1_position_votes.get(pos_idx, {}).items():
            combined_votes[num] += cnt * 0.5  # 50% weight from model consensus
        for num, score in b1_acc_weighted.get(pos_idx, {}).items():
            combined_votes[num] += score * 0.5  # 50% weight from accuracy-weighted

        # Remove already selected numbers
        for used_num in b1_used:
            combined_votes.pop(used_num, None)

        # Validate ranges
        valid_votes = {int(n): v for n, v in combined_votes.items() if 1 <= int(n) <= b1_max}

        if valid_votes:
            best = max(valid_votes, key=valid_votes.get)
            final_b1.append(best)
            b1_used.add(best)
            sorted_top = sorted(valid_votes.items(), key=lambda x: -x[1])[:5]
            b1_details[f'P{pos_idx + 1}'] = {
                'selected': best,
                'votes': {str(n): round(v, 3) for n, v in sorted_top},
                'total_models': len(predictions),
            }
        else:
            # Fallback
            for pred in predictions:
                pb1 = pred.get('b1', [])
                if pos_idx < len(pb1) and pb1[pos_idx] not in b1_used and 1 <= pb1[pos_idx] <= b1_max:
                    final_b1.append(pb1[pos_idx])
                    b1_used.add(pb1[pos_idx])
                    b1_details[f'P{pos_idx + 1}'] = {
                        'selected': pb1[pos_idx],
                        'votes': {str(pb1[pos_idx]): 0.005},
                        'total_models': len(predictions),
                    }
                    break

    final_b1.sort()

    final_b2 = []
    b2_used = set(final_b1)  # No overlap with B1
    b2_details = {}

    for pos_idx in range(pick_b2):
        combined_votes = defaultdict(float)
        for num, cnt in b2_position_votes.get(pos_idx, {}).items():
            combined_votes[num] += cnt * 0.5
        for num, score in b2_acc_weighted.get(pos_idx, {}).items():
            combined_votes[num] += score * 0.5

        for used_num in b2_used:
            combined_votes.pop(used_num, None)

        valid_votes = {int(n): v for n, v in combined_votes.items() if 1 <= int(n) <= b2_max}

        if valid_votes:
            best = max(valid_votes, key=valid_votes.get)
            final_b2.append(best)
            b2_used.add(best)
            sorted_top = sorted(valid_votes.items(), key=lambda x: -x[1])[:5]
            b2_details[f'P{pos_idx + 1}'] = {
                'selected': best,
                'votes': {str(n): round(v, 3) for n, v in sorted_top},
                'total_models': len(predictions),
            }
        else:
            for pred in predictions:
                pb2 = pred.get('b2', [])
                if pos_idx < len(pb2) and pb2[pos_idx] not in b2_used and 1 <= pb2[pos_idx] <= b2_max:
                    final_b2.append(pb2[pos_idx])
                    b2_used.add(pb2[pos_idx])
                    b2_details[f'P{pos_idx + 1}'] = {
                        'selected': pb2[pos_idx],
                        'votes': {str(pb2[pos_idx]): 0.005},
                        'total_models': len(predictions),
                    }
                    break

    final_b2.sort()

    # Compute simple confidence
    total_models = len(predictions)
    model_coverage = min(total_models / max(TOTAL_MODELS, 1), 1.0)

    # Consensus strength
    total_consensus = 0.0
    total_positions = 0
    for details in [b1_details, b2_details]:
        for key, d in details.items():
            votes = d.get('votes', {})
            if votes:
                top_vote = max(votes.values())
                total_votes = sum(votes.values())
                if total_votes > 0:
                    total_consensus += top_vote / total_votes
                    total_positions += 1

    consensus_strength = total_consensus / max(total_positions, 1)

    confidence = {
        'b1_score': min(len(b1_details) / max(pick_b1, 1) * model_coverage, 1.0),
        'b2_score': min(len(b2_details) / max(pick_b2, 1) * model_coverage, 1.0),
        'overall': min((len(b1_details) + len(b2_details)) / max(pick_b1 + pick_b2, 1) * model_coverage, 1.0),
        'consensus_strength': min(consensus_strength, 1.0),
    }

    # v26.0: Build additional analysis blocks with graceful fallback
    freq_pred = {"block1": [], "block2": [], "details": {}}
    top3 = {"models": []}
    try:
        if accuracy_history:
            freq_pred = build_frequency_prediction(
                {'accuracy_history': accuracy_history},
                b1_max, b2_max, pick_b1, pick_b2
            )
    except Exception:
        pass
    try:
        if predictions:
            top3 = build_top3_models({'predictions': predictions, 'accuracy_history': accuracy_history})
    except Exception:
        pass

    # v26.0: Graceful fallback for block1_position if no data
    if not b1_details:
        b1_details = {f'P{i+1}': {'selected': 0, 'votes': {}, 'total_models': 0} for i in range(pick_b1)}
    if not b2_details:
        b2_details = {f'P{i+1}': {'selected': 0, 'votes': {}, 'total_models': 0} for i in range(pick_b2)}

    # v26.2: Compute aggregate number votes across all positions (for full spectrum display)
    b1_all_votes = defaultdict(float)
    b2_all_votes = defaultdict(float)
    for pos_idx in range(pick_b1):
        for num, cnt in b1_position_votes.get(pos_idx, {}).items():
            b1_all_votes[int(num)] += cnt
        for num, score in b1_acc_weighted.get(pos_idx, {}).items():
            b1_all_votes[int(num)] += score
    for pos_idx in range(pick_b2):
        for num, cnt in b2_position_votes.get(pos_idx, {}).items():
            b2_all_votes[int(num)] += cnt
        for num, score in b2_acc_weighted.get(pos_idx, {}).items():
            b2_all_votes[int(num)] += score
    # Convert to sorted list for frontend
    number_spectrum = {
        'block1': sorted([{'number': n, 'votes': round(v, 1)} for n, v in b1_all_votes.items()], key=lambda x: -x['votes']),
        'block2': sorted([{'number': n, 'votes': round(v, 1)} for n, v in b2_all_votes.items()], key=lambda x: -x['votes']),
    }

    return {
        'status': 'ok',
        'game': '',  # Will be set by caller
        'final_prediction': {
            'block1': final_b1,
            'block2': final_b2,
        },
        'block1_position': {
            'prediction': final_b1,
            'confidence': confidence.get('overall', 0.0),
            'details': b1_details,
        },
        'block1_frequency': {
            'prediction': freq_pred.get('block1', []),
            'details': freq_pred.get('details', {}).get('block1', []),
        },
        'block2_position': {
            'prediction': final_b2,
            'confidence': min(len(b2_details) / max(pick_b2, 1) * model_coverage, 1.0),
            'details': b2_details,
        },
        'block2_frequency': {
            'prediction': freq_pred.get('block2', []),
            'details': freq_pred.get('details', {}).get('block2', []),
        },
        'top3_models': top3,
        'confidence': confidence,
        'position_details': {
            'b1': b1_details,
            'b2': b2_details,
        },
        'total_models': total_models,
        'b1_max': b1_max,
        'b2_max': b2_max,
        'pick_b1': pick_b1,
        'pick_b2': pick_b2,
        'draw_type_used': draw_type or 'all',
        'accuracy_entries': len(accuracy_history),
        'number_spectrum': number_spectrum,  # v26.2: full number spectrum
    }


def analyze_from_model_report(model_report_data, game_name, draw_type,
                               top_models, recency, pick_b1, pick_b2):
    """Analyze model report data directly without HTML/CSV."""

    # Reconstruct predictions and accuracy from model report data
    # model_report_data has: {draw_no, draw_type, all_model_predictions, act_b1, act_b2}

    if not model_report_data:
        raise ValueError("Model report data is empty")

    # Get number ranges from data
    all_b1_nums = set()
    all_b2_nums = set()
    for item in model_report_data:
        all_b1_nums.update(item.get('act_b1', []))
        all_b2_nums.update(item.get('act_b2', []))
        for pb1, pb2 in item.get('all_model_predictions', []):
            all_b1_nums.update(pb1)
            all_b2_nums.update(pb2)

    b1_max = max(all_b1_nums) if all_b1_nums else 20
    b2_max = max(all_b2_nums) if all_b2_nums else 20

    # Auto-detect pick counts
    if pick_b1 is None:
        sample = model_report_data[0].get('all_model_predictions', [])
        if sample:
            pick_b1 = len(sample[0][0]) if sample else PICK_B1
        else:
            pick_b1 = PICK_B1
    if pick_b2 is None:
        sample = model_report_data[0].get('all_model_predictions', [])
        if sample:
            pick_b2 = len(sample[0][1]) if sample else PICK_B2
        else:
            pick_b2 = PICK_B2

    # Build predictions from the last entry (most recent predictions)
    last_predictions = model_report_data[-1].get('all_model_predictions', [])
    predictions = []
    for mi, (pb1, pb2) in enumerate(last_predictions):
        predictions.append({
            'model_id': f'p{mi+1}',
            'name': f'Model-{mi+1}',
            'b1': sorted(list(pb1)),
            'b2': sorted(list(pb2)),
        })

    # Build accuracy history
    accuracy_history = []
    for item in model_report_data:
        preds = item.get('all_model_predictions', [])
        act_b1 = item.get('act_b1', [])
        act_b2 = item.get('act_b2', [])
        if preds and act_b1 and act_b2:
            # Use first model's prediction as representative
            pb1, pb2 = preds[0]
            hits_b1 = len(set(pb1) & set(act_b1))
            hits_b2 = len(set(pb2) & set(act_b2))
            accuracy_history.append({
                'draw_no': item['draw_no'],
                'pred_b1': list(pb1),
                'pred_b2': list(pb2),
                'act_b1': act_b1,
                'act_b2': act_b2,
                'hits_b1': hits_b1,
                'hits_b2': hits_b2,
                'total': hits_b1 + hits_b2,
                'draw_type': item.get('draw_type', 'unknown'),
            })

    result = analyze_from_pipeline_data(
        predictions, accuracy_history,
        b1_max, b2_max, pick_b1, pick_b2,
        draw_type, top_models, recency
    )
    result['game'] = game_name
    result['source'] = 'model_report'

    return result


